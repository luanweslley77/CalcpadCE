/**
 * Imports exact matches from the committed VS Code shared-UI index and
 * language-pack subset into the pt-BR catalog. Offline and deterministic;
 * --check verifies the committed output in CI.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const frontend = path.resolve(here, '..');
const messages = path.join(frontend, 'calcpad-frontend/src/i18n/messages');
const indexFile = path.join(here, 'vscode-shared-ui.index.json');
const packFile = path.join(here, 'vscode-shared-ui.langpack.pt-BR.json');
const exceptionsFile = path.join(here, 'vscode-shared-ui.exceptions.json');
const catalogFile = path.join(messages, 'pt-BR.ts');
const provenanceFile = path.join(messages, 'provenance.pt-BR.json');

const check = process.argv.includes('--check');
const index = JSON.parse(fs.readFileSync(indexFile, 'utf8'));
const pack = JSON.parse(fs.readFileSync(packFile, 'utf8'));
const exceptions = JSON.parse(fs.readFileSync(exceptionsFile, 'utf8'));
const overrides = exceptions.overrides ?? {};
const exclude = exceptions.exclude ?? {};
const errors = [];

const selected = {};
for (const [english, entries] of Object.entries(index.keys ?? {})) {
    if (english in exclude) {
        if (english in overrides) errors.push(`"${english}" is both overridden and excluded`);
        continue;
    }
    const translations = new Set();
    for (const { module, key } of entries) {
        const value = pack.contents?.[module]?.[key];
        if (value) translations.add(value);
    }
    if (translations.size === 0) {
        errors.push(`"${english}" has no translation in the committed langpack subset`);
        continue;
    }
    if (english in overrides) {
        const chosen = overrides[english];
        if (!translations.has(chosen))
            errors.push(`"${english}" override "${chosen}" is not one of: ${[...translations].join(', ')}`);
        else selected[english] = chosen;
        continue;
    }
    if (translations.size === 1) {
        selected[english] = [...translations][0];
        continue;
    }
    errors.push(`"${english}" has multiple translations and needs an override or exclude: ${[...translations].join(', ')}`);
}

for (const key of Object.keys(overrides)) {
    if (!(key in (index.keys ?? {}))) errors.push(`override "${key}" is not in the index`);
}
for (const key of Object.keys(exclude)) {
    if (!(key in (index.keys ?? {}))) errors.push(`exclude "${key}" is not in the index`);
}

const sorted = {};
for (const key of Object.keys(selected).sort((a, b) => a.localeCompare(b))) sorted[key] = selected[key];
const pins = pack.vscode;

const lines = Object.entries(sorted).map(
    ([key, value]) => `    ${JSON.stringify(key)}: ${JSON.stringify(value)},`,
);
const catalog = `// Generated by scripts/import-vscode-shared-ui.mjs from VS Code ${pins.tag}
// and ${pins.pack} ${pins.locTag}. Do not edit.
const ptBR: Record<string, string> = {
${lines.join('\n')}
}

export default ptBR
`;

const provenance = {
    locale: 'pt-BR',
    vscode: pins,
    keys: Object.fromEntries(Object.keys(sorted).map(key => [key, { source: 'vscode-shared-ui' }])),
};
const provenanceText = JSON.stringify(provenance, null, 2) + '\n';

if (errors.length) {
    console.error('VS Code shared-UI import failed:');
    for (const error of errors) console.error(`- ${error}`);
    process.exitCode = 1;
} else if (check) {
    const currentCatalog = fs.existsSync(catalogFile) ? fs.readFileSync(catalogFile, 'utf8') : '';
    const currentProvenance = fs.existsSync(provenanceFile) ? fs.readFileSync(provenanceFile, 'utf8') : '';
    if (currentCatalog !== catalog || currentProvenance !== provenanceText) {
        console.error('pt-BR shared-UI catalog is out of date; run:');
        console.error('  node scripts/import-vscode-shared-ui.mjs');
        process.exitCode = 1;
    } else {
        console.log(`VS Code shared-UI pt-BR: ${Object.keys(sorted).length} keys, up to date.`);
    }
} else {
    fs.writeFileSync(catalogFile, catalog);
    fs.writeFileSync(provenanceFile, provenanceText);
    console.log(`VS Code shared-UI pt-BR: ${Object.keys(sorted).length} keys (${Object.keys(exclude).length} excluded).`);
}
